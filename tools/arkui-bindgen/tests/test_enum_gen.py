"""A0 验收测试：libclang 解析 + 枚举发射（fixture 头文件，自包含）。"""
from pathlib import Path

from arkui_bindgen.emit_csharp import emit_enum_file, emit_enum_json
from arkui_bindgen.parse import parse_headers

FIX = Path(__file__).parent / "fixtures"


def _model():
    return parse_headers([FIX / "mini_enums.h"], [FIX])


def test_parse_named_and_anonymous_enums():
    m = _model()
    assert "ArkUI_Color" in m.enums
    assert m.enums["ArkUI_Color"].members[0].value == 0
    assert m.enums["ArkUI_Color"].members[1].value == 1
    # 匿名枚举归一采用 typedef 名；表达式值由 libclang 求值
    assert "UI_TouchEventAction" in m.enums
    vals = {x.name: x.value for x in m.enums["UI_TouchEventAction"].members}
    assert vals == {"UI_TOUCH_EVENT_ACTION_CANCEL": 0, "UI_TOUCH_EVENT_ACTION_DOWN": (1 << 1)}


def test_parse_transitively_included_enum_not_harvested():
    # helper.h 经传递 include 进来，但收割面只允许显式列出的头文件
    m = _model()
    assert len(m.enums) == 2                # mini_enums.h 只收自己两个，传递 include 不收割
    assert "HelperEnum" not in m.enums


def test_emit_enum_file_byte_layout(tmp_path):
    src = tmp_path / "emit_order.h"
    src.write_text("typedef enum { E_A = 0, E_B = 2, E_C } MixE;\n", encoding="utf-8")
    m = parse_headers([src], [tmp_path])
    text = emit_enum_file(m.enums, ["MixE"], "emit_order.h", tool="t")
    lines = text.split("\n")
    assert lines[0].startswith("// <auto-generated>由 t ")
    assert lines[2] == "#nullable enable"
    assert lines[4] == "namespace HarmonyOS.Bindings.NativeNode;"
    assert "public enum MixE" in lines
    assert "    E_B = 2," in lines
    assert "    E_C = 3," in lines
    assert lines[-1] == ""                  # 枚举块后空行（含文件末尾）


def test_emit_enum_json_shape():
    m = _model()
    text = emit_enum_json(m.enums)
    assert text.startswith("{\n")
    assert '"UI_TOUCH_EVENT_ACTION_CANCEL": 0' in text
