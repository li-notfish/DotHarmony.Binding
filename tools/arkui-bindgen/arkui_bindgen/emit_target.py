"""目标装配：code_targets 里的一个条目 → 完整 .g.cs 文件文本。

文件骨架（与手写镜像文件的既有结构对齐）：
  auto-generated 注释（含来源头文件与语义配置指针）
  #nullable enable / using System; / using System.Runtime.InteropServices;
  namespace HarmonyOS.Bindings.NativeNode;
  #pragma warning disable CS8500
  枚举（internal 组） → 不透明类型 → ABI 结构体（含 inline-array 包装） → 函数表 struct
  → internal static unsafe partial class <container> { [LibraryImport] 组 }
  #pragma warning restore CS8500
"""
from __future__ import annotations

from .emit_csharp import Emitter
from .model import Model


def emit_code_target(name: str, tgt: dict, model: Model, sem) -> str:
    emitter = Emitter(sem._raw)
    per_type = tgt.get("per_type", {})
    per_fn = tgt.get("per_fn", {})
    per_enum = tgt.get("per_enum", {})

    lines: list[str] = []
    src = ", ".join(sorted({h for h in _sources(tgt, model)}))
    lines.append(f"// <auto-generated>由 tools/arkui-bindgen 从 HarmonyOS NDK 头文件生成（语义规则见"
                 f" tools/arkui-bindgen/config/semantics.yaml），请勿手工编辑</auto-generated>")
    lines.append(f"// 来源: {src}")
    if tgt.get("doc"):
        for dl in tgt["doc"].splitlines():
            lines.append(f"// {dl}")
    lines.append("#nullable enable")
    lines.append("using System;")
    lines.append("using System.Runtime.CompilerServices;")
    lines.append("using System.Runtime.InteropServices;")
    lines.append("")
    lines.append("namespace HarmonyOS.Bindings.NativeNode;")
    lines.append("")
    lines.append("#pragma warning disable CS8500")
    lines.append("")

    emitted_enums: list[str] = []
    for e_name in tgt.get("enums", []):
        e = model.enums.get(e_name)
        if e is None:
            raise KeyError(f"目标 {name}: 枚举 {e_name} 未在头文件集合中解析到")
        lines.extend(emitter.emit_enum_configured(e, per_enum.get(e_name, {})))
        lines.append("")
        emitted_enums.append(e_name)

    for o_name in tgt.get("opaque", []):
        o_doc = ""
        if isinstance(o_name, dict):
            o_doc = o_name.get("doc", "")
            o_name = o_name["name"]
        vis = emitter.opaque_emit.get(o_name, "internal")
        for dl in str(o_doc).splitlines():
            if dl:
                lines.append(dl)
        lines.extend(emitter.emit_opaque(o_name, vis))
        lines.append("")

    for t_name in tgt.get("types", []):
        s = model.structs.get(t_name)
        if s is None:
            raise KeyError(f"目标 {name}: 结构体 {t_name} 未在头文件集合中解析到")
        tcfg = dict(per_type.get(t_name, {}))
        # inline-array 包装类型的伴生发射（在宿主结构体之前）
        for fld, wrapper in tcfg.get("inline_arrays", {}).items():
            f = next((x for x in s.fields if x.name == fld.split(".")[-1]), None)
            if f is None or f.ctype.kind != "array":
                raise KeyError(f"{t_name}.{fld} 不是内联数组字段")
            elem = emitter.cs_type(f.ctype.pointee, "field")
            lines.extend(emitter.emit_inline_array_wrapper(
                wrapper, elem, f.ctype.count, tcfg.get("visibility", "internal")))
            lines.append("")
        lines.extend(emitter.emit_struct(s, tcfg))
        lines.append("")

    for t_name in tgt.get("fn_tables", []):
        s = model.structs.get(t_name)
        if s is None:
            raise KeyError(f"目标 {name}: 函数表 {t_name} 未在头文件集合中解析到")
        lines.extend(emitter.emit_struct(s, per_type.get(t_name, {})))
        lines.append("")

    container = tgt.get("container", {})
    fns = tgt.get("functions", [])
    if fns:
        cls = container.get("class", "ArkUINativeApi")
        lib = container.get("lib_const", "ArkuiLib")
        vis_default = container.get("visibility", "private")
        lines.append(f"internal static unsafe partial class {cls}")
        lines.append("{")
        for i, f_name in enumerate(fns):
            fn = model.functions.get(f_name)
            if fn is None:
                raise KeyError(f"目标 {name}: 函数 {f_name} 未在头文件集合中解析到")
            fcfg = {"visibility": vis_default, **per_fn.get(f_name, {})}
            seg = emitter.emit_function(fn, fcfg, lib)
            for sl in seg:
                lines.append("    " + sl)
            lines.append("")
        if lines and lines[-1] == "":
            lines.pop()
        lines.append("}")
        lines.append("")

    if lines and lines[-1] == "":
        lines.pop()
    lines.append("")
    lines.append("#pragma warning restore CS8500")
    lines.append("")
    return "\n".join(lines)


def _sources(tgt: dict, model: Model) -> set[str]:
    headers: set[str] = set()
    for e in tgt.get("enums", []):
        if e in model.enums:
            headers.add(model.enums[e].header)
    for t in tgt.get("types", []) + tgt.get("fn_tables", []):
        if t in model.structs:
            headers.add(model.structs[t].header)
    for f in tgt.get("functions", []):
        if f in model.functions:
            headers.add(model.functions[f].header)
    return headers
