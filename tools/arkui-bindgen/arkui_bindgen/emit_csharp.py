"""C# 发射器。A0 先只覆盖枚举（逐字节对齐 ArkUINodeTypes.g.cs 现格式）；
A2 起扩展 ABI 结构体 / 函数表 / [LibraryImport]。

现格式锚点（git 历史 ArkUINodeTypes.g.cs 与旧 extract_arkui_types.py 一致）：
  - UTF-8 无 BOM、LF 行尾
  - 头两行注释 + #nullable enable + 空行 + namespace 声明 + 空行
  - 枚举按名字排序；成员按声明顺序、显式值 NAME = v,；重复成员名去重
  - 每个枚举块后跟一个空行（含文件末尾）
"""
from __future__ import annotations

import json

from .model import EnumModel

LEGACY_HEADER_TOOL = "src/nativeBinding/extract_arkui_types.py"
HEADER_TOOL = "tools/arkui-bindgen"


def render_enum(name: str, members) -> list[str]:
    lines = [f"public enum {name}", "{"]
    seen: set[str] = set()
    for m in members:
        cs_name = m.name
        if cs_name in seen:
            continue
        seen.add(cs_name)
        lines.append(f"    {cs_name} = {m.value},")
    lines.append("}")
    return lines


def emit_enum_file(
    enums: dict[str, EnumModel],
    wanted: list[str],
    source_desc: str,
    tool: str = HEADER_TOOL,
) -> str:
    """生成 ArkUINodeTypes.g.cs 内容（字节级复现旧产物格式）。"""
    out: list[str] = [
        f"// <auto-generated>由 {tool} 从 HarmonyOS NDK 头文件生成，请勿手工编辑</auto-generated>",
        f"// 源头文件: {source_desc}",
        "#nullable enable",
        "",
        "namespace HarmonyOS.Bindings.NativeNode;",
        "",
    ]
    for name in sorted(wanted):
        if name not in enums:
            continue
        out.extend(render_enum(name, enums[name].members))
        out.append("")
    return "\n".join(out)


def emit_enum_json(enums: dict[str, EnumModel]) -> str:
    """生成 ArkUINodeTypes.json（{枚举名: {成员: 值}}，含全部已解析枚举）。

    与旧脚本行为一致：json.dumps(indent=0, sort_keys=True)，LF 收尾。
    """
    dump = {name: {m.name: m.value for m in e.members} for name, e in enums.items()}
    return json.dumps(dump, indent=0, sort_keys=True)


# ═══════════════════════════ 以下为 A2：类型/函数表/PInvoke 发射 ═══════════════════════════

from .model import CType, FunctionModel, StructModel

# C 基元拼写 → C# 拼写（musl LP64：long 为 64 位）
BUILTIN_CS = {
    "void": "void",
    "char": "sbyte", "signed char": "sbyte", "unsigned char": "byte",
    "char16_t": "char", "char32_t": "uint",
    "short": "short", "unsigned short": "ushort",
    "int": "int", "unsigned int": "uint",
    "long": "long", "unsigned long": "ulong",
    "long long": "long", "unsigned long long": "ulong",
    "float": "float", "double": "double",
    "int8_t": "sbyte", "uint8_t": "byte", "int16_t": "short", "uint16_t": "ushort",
    "int32_t": "int", "uint32_t": "uint", "int64_t": "long", "uint64_t": "ulong",
    "size_t": "UIntPtr", "intptr_t": "IntPtr", "uintptr_t": "UIntPtr",
    "bool": "bool", "_Bool": "bool",
}

# 基元字节数（union/ExplicitSize 计算用）
BUILTIN_BYTES = {
    "float": 4, "double": 8,
    "int8_t": 1, "uint8_t": 1, "int16_t": 2, "uint16_t": 2,
    "int32_t": 4, "uint32_t": 4, "int64_t": 8, "uint64_t": 8,
    "int": 4, "unsigned int": 4, "long": 8, "unsigned long": 8,
}

CS_KEYWORDS = {
    "event", "string", "object", "namespace", "params", "ref", "out", "in",
    "base", "base", "default", "checked", "operator", "internal",
}


class EmitError(Exception):
    """配置缺口或不可映射类型：宁可报错也不猜。"""


class _Ctx:
    """发射上下文：当前处于 delegate* unmanaged / pinvoke / struct 字段 哪种环境。"""
    FIELD = "field"          # struct 普通字段
    FNPTR = "fnptr"          # delegate* unmanaged<...> 的参数/返回
    PINVOKE = "pinvoke"      # [LibraryImport] 参数/返回


def _pascal(name: str) -> str:
    return name[:1].upper() + name[1:] if name else name


def _escape(name: str) -> str:
    return "@" + name if name in CS_KEYWORDS else name


class Emitter:
    """目标文件发射器：所有策略从 Semantics 读取。"""

    def __init__(self, cfg: dict) -> None:
        self.cfg = cfg
        self.alias_overrides: dict = cfg.get("alias_overrides", {})
        self.handwritten_aliases: set = set(cfg.get("handwritten_aliases", []))
        # 托管包装类型：C 侧是不透明指针，C# 侧手写 readonly struct 句柄包装，
        # fnptr 中按值呈现（8 字节指针尺寸，ABI 一致）。如 ArkUI_GestureRecognizer。
        self.managed_wrappers: set = set(cfg.get("managed_wrappers", []))
        self.opaque_emit: dict = cfg.get("opaque_emit", {})          # name -> visibility
        self.defaults = cfg.get("defaults", {})
        self.bool_policy = cfg.get("bool", {})
        self.enum_visibility: dict = cfg.get("enum_visibility", {})

    # ── 类型映射 ──
    def cs_type(self, t: CType, ctx: str) -> str:
        kind = t.kind
        if kind == "builtin":
            name = BUILTIN_CS.get(t.name)
            if name is None and t.name in self.alias_overrides:
                # typedef 到基元的语义别名（如 ArkUI_GestureDirectionMask 实为
                # uint32_t，但手写面以 flags 枚举 ArkUI_GestureDirection 表达）
                return self.alias_overrides[t.name]
            if name is None:
                raise EmitError(f"未映射的 C 基元拼写: {t.name!r}（加入 builtin_map 或 errata）")
            if name == "bool":
                if ctx == _Ctx.FNPTR:
                    return self.bool_policy.get("unmanaged_fnptr", "byte")
                if ctx == _Ctx.FIELD:
                    return "byte"
                return "bool"  # pinvoke：由调用点补 [MarshalAs(UnmanagedType.U1)]
            return name
        if kind == "enum":
            return self.enum_name(t.name)
        if kind == "struct":
            return t.name
        if kind == "opaque":
            if t.name in self.managed_wrappers:
                return t.name
            return t.name if t.name in self.opaque_emit else self.defaults.get("opaque_value", "IntPtr")
        if kind == "alias":
            if t.name in self.handwritten_aliases:
                return t.name
            if t.name in self.alias_overrides:
                return self.alias_overrides[t.name]
            raise EmitError(
                f"未声明的句柄别名 {t.name!r}：加入 alias_overrides 或 handwritten_aliases")
        if kind == "pointer":
            p = t.pointee
            if p.kind == "builtin" and p.name == "void":
                return "void*"
            if p.kind == "builtin" and BUILTIN_CS.get(p.name) in ("sbyte", "byte"):
                return "byte*"
            if p.kind == "builtin" and BUILTIN_CS.get(p.name) == "char":
                return "ushort*"
            if p.kind == "opaque":
                if p.name in self.managed_wrappers:
                    return p.name
                if p.name in self.opaque_emit:
                    return f"{p.name}*"
                if p.name in self.handwritten_aliases:
                    return p.name
                return self.defaults.get("opaque_pointer", "IntPtr")
            if p.kind == "struct":
                return f"{p.name}*"
            if p.kind == "enum":
                return f"{self.enum_name(p.name)}*"
            if p.kind == "pointer":
                raise EmitError("多级指针需要 errata 显式指定映射")
            if p.kind == "fnptr":
                return self.cs_type(p, ctx)
            if p.kind == "builtin":
                return f"{self.cs_type(p, ctx)}*"
            raise EmitError(f"未映射的指针指向类型: {p.kind} {p.name!r}")
        if kind == "fnptr":
            args = [self.cs_type(a, _Ctx.FNPTR) for a in t.args]
            ret = self.cs_type(t.ret, _Ctx.FNPTR)
            if ret == "bool":
                ret = self.bool_policy.get("unmanaged_fnptr", "byte")
            return "delegate* unmanaged<" + ", ".join(args + [ret]) + ">"
        if kind == "array":
            raise EmitError(f"内联数组需经 inline_arrays 配置包装（元素 {t.pointee.name}×{t.count}）")
        raise EmitError(f"未知类型 kind: {kind}")

    def enum_name(self, c_name: str) -> str:
        return self.cfg.get("enum_renames", {}).get(c_name, c_name)

    # ── 结构体 / 函数表发射 ──
    def emit_struct(self, s: StructModel, tcfg: dict) -> list[str]:
        vis = tcfg.get("visibility", "internal")
        field_case = tcfg.get("field_case", "preserve")
        member_case = tcfg.get("member_case", field_case)
        inline_arrays = tcfg.get("inline_arrays", {})
        member_overrides = tcfg.get("member_overrides", {})
        lines: list[str] = []
        for dl in str(tcfg.get("doc", "") or "").splitlines():
            if dl:
                lines.append(dl)
        if s.is_union:
            size = tcfg.get("explicit_size")
            if size is None:
                size = max(BUILTIN_BYTES.get(f.ctype.name, 0) for f in s.fields)
            lines.append(f"[StructLayout(LayoutKind.Explicit, Size = {size})]")
            unsafe_kw = "unsafe " if self._struct_needs_unsafe(s, tcfg) else ""
            lines.append(f"{vis} {unsafe_kw}struct {s.name}".replace("  ", " "))
            lines.append("{")
            for f in s.fields:
                lines.append(f"    [FieldOffset(0)] public {self.cs_type(f.ctype, _Ctx.FIELD)} {f.name};")
            lines.append("}")
            return lines

        lines.append("[StructLayout(LayoutKind.Sequential)]")
        unsafe_kw = "unsafe " if self._struct_needs_unsafe(s, tcfg) else ""
        lines.append(f"{vis} {unsafe_kw}struct {s.name}".replace("  ", " "))
        lines.append("{")
        for f in s.fields:
            t = f.ctype
            fname = f.name
            if f"{s.name}.{f.name}" in inline_arrays or f.name in inline_arrays:
                wrapper = inline_arrays.get(f"{s.name}.{f.name}", inline_arrays.get(f.name, ""))
                cs = wrapper
            elif f.name in member_overrides:
                # 逐成员勘误：手写面与默认映射不一致时，声明式给出最终 C# 类型文本
                cs = member_overrides[f.name]
                case = member_case if t.kind == "fnptr" else field_case
                if case == "pascal":
                    fname = _pascal(fname)
                fname = _escape(fname)
                lines.append(f"    public {cs} {fname};")
                continue
            elif t.kind == "array":
                raise EmitError(f"{s.name}.{f.name} 是内联数组，需在 inline_arrays 声明 wrapper 名")
            else:
                ctx = _Ctx.FNPTR if t.kind == "fnptr" else _Ctx.FIELD
                cs = self.cs_type(t, ctx)
                case = member_case if t.kind == "fnptr" else field_case
                if case == "pascal":
                    fname = _pascal(fname)
                fname = _escape(fname)
            lines.append(f"    public {cs} {fname};")
        lines.append("}")
        return lines

    def _struct_needs_unsafe(self, s: StructModel, tcfg: dict) -> bool:
        inline_arrays = tcfg.get("inline_arrays", {})
        for f in s.fields:
            if f"{s.name}.{f.name}" in inline_arrays or f.name in inline_arrays:
                continue
            t = f.ctype
            if t.kind in ("pointer", "fnptr", "array"):
                return True
            if t.kind == "builtin" and t.name == "bool":
                continue
        return False

    def emit_inline_array_wrapper(self, wrapper: str, element_cs: str, count: int,
                                  visibility: str = "internal") -> list[str]:
        return [
            f"[InlineArray({count})]",
            f"{visibility} struct {wrapper}",
            "{",
            f"    private {element_cs} _e0;",
            "}",
        ]

    # ── 不透明类型 ──
    def emit_opaque(self, name: str, visibility: str = "internal") -> list[str]:
        return [f"{visibility} struct {name} {{ }}"]

    # ── PInvoke 函数发射 ──
    def emit_function(self, fn: FunctionModel, fcfg: dict, lib_const: str) -> list[str]:
        vis = fcfg.get("visibility", "private")
        ret_over = fcfg.get("ret")
        param_over: dict = fcfg.get("params", {})

        def map_param(p) -> str:
            over = param_over.get(p.name) if isinstance(param_over, dict) else None
            if over:
                over = str(over)
                # 含空格 → 视为完整参数文本（type + 名字，支持改名/加 out 等修饰）
                if " " in over.strip():
                    return over
                return f"{over} {_escape(p.name)}"
            cs = self.cs_type(p.ctype, _Ctx.PINVOKE)
            if cs == "bool":
                return f"[MarshalAs(UnmanagedType.U1)] bool {_escape(p.name)}"
            return f"{cs} {_escape(p.name)}"

        lines: list[str] = []
        doc = fcfg.get("doc")
        if doc:
            for dl in str(doc).splitlines():
                lines.append(dl)
        lines.append(f"[LibraryImport({lib_const})]")
        if ret_over:
            ret = ret_over
        else:
            ret = self.cs_type(fn.ret, _Ctx.PINVOKE)
        if fn.args:
            args_s = ", ".join(map_param(a) for a in fn.args)
        else:
            args_s = ""
        sig = f"{vis} static partial {ret} {fn.name}({args_s});"
        lines.append(sig)
        return lines

    # ── 配置化枚举发射（visible/flags/combo/前缀剥离/值格式）──
    def emit_enum_configured(self, e: EnumModel, ecfg: dict) -> list[str]:
        vis = ecfg.get("visibility", "public")
        name = self.enum_name(e.name)
        prefix = ecfg.get("member_prefix_strip", "")
        suffix = ecfg.get("member_suffix_strip", "")
        vfmt = ecfg.get("value_format", "decimal")
        value_overrides: dict = ecfg.get("value_overrides", {})

        def fmt(v: int) -> str:
            if vfmt == "hex":
                return f"0x{v:02X}"
            if vfmt == "binary":
                return "0b" + format(v, "04b")
            return str(v)

        lines: list[str] = []
        for dl in str(ecfg.get("doc", "") or "").splitlines():
            if dl:
                lines.append(dl)
        if ecfg.get("flags"):
            lines.append("[Flags]")
        lines.append(f"{vis} enum {name}")
        lines.append("{")
        seen: set[str] = set()
        for m in e.members:
            cs_name = m.name[len(prefix):] if prefix and m.name.startswith(prefix) else m.name
            if suffix and cs_name.endswith(suffix):
                cs_name = cs_name[:-len(suffix)]
            if ecfg.get("member_case") == "pascal":
                if cs_name == cs_name.upper():
                    cs_name = "".join(p.capitalize() for p in cs_name.split("_"))
                else:
                    cs_name = _pascal(cs_name)
            if cs_name in seen:
                continue
            seen.add(cs_name)
            doc_since = ""
            if "@since" in (m.doc or ""):
                import re as _re
                mo = _re.search(r"@since\s+(\S+)", m.doc)
                if mo:
                    doc_since = mo.group(1)
            if doc_since:
                lines.append(f"    /// <summary>@since {doc_since}</summary>")
            over = value_overrides.get(cs_name)
            if over is not None:
                if isinstance(over, dict):
                    expr, oc = over["expr"], over.get("comment", "")
                else:
                    expr, oc = str(over), ""
                tail = f" // {oc}" if oc else ""
                lines.append(f"    {cs_name} = {expr},{tail}")
            else:
                lines.append(f"    {cs_name} = {fmt(m.value)},")
        for combo_name, combo in (ecfg.get("named_combos") or {}).items():
            comment = f" // {combo['comment']}" if combo.get("comment") else ""
            lines.append(f"    {combo_name} = {combo['expr']},{comment}")
        lines.append("}")
        return lines
